from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Dict, List, Optional
import datetime
import uuid

from .context import SourceReference


class WorkflowActionRisk(str, Enum):
    """
    Risk classification for proposed workflow steps.
    Non-negotiable rule: consequential/risky actions default to requiring explicit user approval.
    """
    READ_ONLY = "read_only"
    IDEMPOTENT_WRITE = "idempotent_write"
    CONSEQUENTIAL = "consequential"


@dataclass(frozen=True)
class WorkflowStepProposal:
    """
    A single proposed action step within a multi-step workflow.

    Fields:
    - step_id (str): Unique UUID v4 string identifying this step proposal.
    - step_number (int): 1-indexed sequential execution order.
    - tool_name (str): Allow-listed tool name to be invoked (e.g. 'calendar.add_event', 'email.draft').
    - arguments (Dict[str, Any]): Validated parameter dictionary for the tool invocation.
    - description (str): Human-readable explanation of what this step does.
    - risk_level (WorkflowActionRisk): Risk classification.
    - requires_approval (bool): Whether execution must pause for explicit user confirmation.
    - timeout_seconds (float): Maximum permissible execution time for this step.
    """
    step_id: str
    step_number: int
    tool_name: str
    arguments: Dict[str, Any]
    description: str
    risk_level: WorkflowActionRisk = WorkflowActionRisk.CONSEQUENTIAL
    requires_approval: bool = True
    timeout_seconds: float = 30.0

    def to_dict(self) -> Dict[str, Any]:
        return {
            "step_id": self.step_id,
            "step_number": self.step_number,
            "tool_name": self.tool_name,
            "arguments": self.arguments,
            "description": self.description,
            "risk_level": self.risk_level.value if isinstance(self.risk_level, WorkflowActionRisk) else str(self.risk_level),
            "requires_approval": self.requires_approval,
            "timeout_seconds": self.timeout_seconds,
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> WorkflowStepProposal:
        risk = data.get("risk_level", WorkflowActionRisk.CONSEQUENTIAL)
        if isinstance(risk, str):
            risk = WorkflowActionRisk(risk)
        return cls(
            step_id=str(data["step_id"]),
            step_number=int(data["step_number"]),
            tool_name=str(data["tool_name"]),
            arguments=dict(data.get("arguments", {})),
            description=str(data["description"]),
            risk_level=risk,
            requires_approval=bool(data.get("requires_approval", True)),
            timeout_seconds=float(data.get("timeout_seconds", 30.0)),
        )


@dataclass(frozen=True)
class WorkflowProposal:
    """
    Canonical proposal generated by Reasoning Engine for downstream W4 workflow execution.

    Fields:
    - proposal_id (str): Unique UUID v4 string identifying this proposal.
    - session_id (str): Active voicebot session identifier.
    - correlation_id (str): UUID string for end-to-end tracing across modules.
    - goal (str): High-level user goal or intent statement.
    - suggested_action (str): Summary of recommended action.
    - steps (List[WorkflowStepProposal]): Ordered list of action steps proposed.
    - sources_used (List[SourceReference]): Citations to the context items justifying this proposal.
    - confidence (float): Numerical confidence score in range [0.0 - 1.0].
    - requires_user_approval (bool): True if any step is consequential or requires user consent.
    - is_mock (bool): True if generated via mock reasoning pipeline. Constraint: Always True.
    - created_at (str): ISO 8601 UTC creation timestamp.
    - metadata (Dict[str, Any]): Additional operational and audit metadata.
    """
    proposal_id: str
    session_id: str
    correlation_id: str
    goal: str
    suggested_action: str
    steps: List[WorkflowStepProposal] = field(default_factory=list)
    sources_used: List[SourceReference] = field(default_factory=list)
    confidence: float = 1.0
    requires_user_approval: bool = True
    is_mock: bool = True
    created_at: str = field(
        default_factory=lambda: datetime.datetime.now(datetime.timezone.utc).isoformat()
    )
    metadata: Dict[str, Any] = field(default_factory=dict)

    @classmethod
    def create(
        cls,
        session_id: str,
        correlation_id: str,
        goal: str,
        suggested_action: str,
        steps: Optional[List[WorkflowStepProposal]] = None,
        sources_used: Optional[List[SourceReference]] = None,
        confidence: float = 1.0,
        metadata: Optional[Dict[str, Any]] = None,
    ) -> WorkflowProposal:
        steps_list = steps or []
        # If any step requires approval, the entire proposal requires approval
        requires_approval = any(s.requires_approval for s in steps_list) if steps_list else True
        return cls(
            proposal_id=str(uuid.uuid4()),
            session_id=session_id,
            correlation_id=correlation_id,
            goal=goal,
            suggested_action=suggested_action,
            steps=steps_list,
            sources_used=sources_used or [],
            confidence=confidence,
            requires_user_approval=requires_approval,
            is_mock=True,
            metadata=metadata or {},
        )

    def to_dict(self) -> Dict[str, Any]:
        return {
            "proposal_id": self.proposal_id,
            "session_id": self.session_id,
            "correlation_id": self.correlation_id,
            "goal": self.goal,
            "suggested_action": self.suggested_action,
            "steps": [s.to_dict() for s in self.steps],
            "sources_used": [src.to_dict() for src in self.sources_used],
            "confidence": self.confidence,
            "requires_user_approval": self.requires_user_approval,
            "is_mock": self.is_mock,
            "created_at": self.created_at,
            "metadata": self.metadata,
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> WorkflowProposal:
        steps = [
            WorkflowStepProposal.from_dict(s) if isinstance(s, dict) else s
            for s in data.get("steps", [])
        ]
        sources = [
            SourceReference.from_dict(src) if isinstance(src, dict) else src
            for src in data.get("sources_used", [])
        ]
        return cls(
            proposal_id=str(data["proposal_id"]),
            session_id=str(data["session_id"]),
            correlation_id=str(data["correlation_id"]),
            goal=str(data["goal"]),
            suggested_action=str(data["suggested_action"]),
            steps=steps,
            sources_used=sources,
            confidence=float(data.get("confidence", 1.0)),
            requires_user_approval=bool(data.get("requires_user_approval", True)),
            is_mock=bool(data.get("is_mock", True)),
            created_at=str(data.get("created_at", datetime.datetime.now(datetime.timezone.utc).isoformat())),
            metadata=dict(data.get("metadata", {})),
        )
